// Emit d1/seed-parishes.sql from seeds/parishes.js.
//
// The D1 seed is generated rather than hand-written so it can't drift from the
// list the Node app seeds. Re-run after adding a parish:
//
//   node scripts/gen-seed-sql.js
//
// AGORA_DB_PATH is set only because requiring seeds/parishes.js pulls in db.js,
// which refuses to load without it. No database is opened.
process.env.AGORA_DB_PATH = process.env.AGORA_DB_PATH || '/dev/null';

const fs = require('fs');
const path = require('path');
const { parishes, schedules } = require('../seeds/parishes');

const q = (v) => (v === null || v === undefined || v === '')
  ? 'NULL'
  : `'${String(v).replace(/'/g, "''")}'`;

// Provenance: we know where each parish came from, but not when it was last
// checked — so verified_at stays NULL rather than inventing a date. The UI
// reads that as "never verified", which is both true and the call to action.
function provenance(p) {
  return p.website
    ? { type: 'website', ref: p.website }
    : { type: 'import', ref: 'seeds/parishes.js' };
}

const lines = [];
lines.push('-- Agora — parish seed for D1. GENERATED by scripts/gen-seed-sql.js.');
lines.push('-- Edit seeds/parishes.js and re-run; do not hand-edit this file.');
lines.push('--');
lines.push('--   wrangler d1 execute agora --remote --file=d1/seed-parishes.sql');
lines.push('--');
lines.push('-- Every seeded parish is in NSW, so the Australia/Sydney default applies.');
lines.push('-- A parish outside that zone must set timezone explicitly.');
lines.push('');

for (const p of parishes) {
  const pr = provenance(p);
  lines.push(
    'INSERT INTO parishes (id, name, full_name, jurisdiction, address, lat, lng, ' +
    'website, languages, color, info_source_type, info_source_ref) VALUES (\n' +
    `  ${q(p.id)}, ${q(p.name)}, ${q(p.full_name)}, ${q(p.jurisdiction)}, ${q(p.address)},\n` +
    `  ${p.lat}, ${p.lng}, ${q(p.website)}, ${q(p.languages || '["English"]')}, ${q(p.color)},\n` +
    `  ${q(pr.type)}, ${q(pr.ref)}\n) ON CONFLICT(id) DO NOTHING;`
  );
}

lines.push('');
lines.push('-- Recurrence rules. start_time/end_time are LOCAL wall clock in the');
lines.push("-- parish's timezone — not UTC. See d1/schema.sql.");
lines.push('');

for (const s of schedules) {
  lines.push(
    'INSERT INTO schedules (parish_id, day_of_week, start_time, end_time, title, event_type) ' +
    `VALUES (${q(s.parish_id)}, ${s.day_of_week}, ${q(s.start_time)}, ${q(s.end_time)}, ` +
    `${q(s.title)}, ${q(s.event_type)});`
  );
}
lines.push('');

const out = path.join(__dirname, '..', 'd1', 'seed-parishes.sql');
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out} — ${parishes.length} parishes, ${schedules.length} schedules`);
